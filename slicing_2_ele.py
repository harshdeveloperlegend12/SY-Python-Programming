# Create a list containing 8 elements
list = [10, 20, 30, 40, 50, 60, 70, 80]

# Slice every second element starting from the first element 
# Leaving start and stop empty defaults to the beginning and end of the list
new_list = list[::2]

# Print the result
print("Original List:", list)
print("Sliced List (every second element):", new_list)
