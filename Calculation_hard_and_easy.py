a=float(input("Enter the value of a: "))
b=float(input("Enter the value of b: "))

#Addition
c=a+b
print("Addition of",a,"&",b,"is: ",c)

#Subtraction
c=a-b
print("Subtraction of",a,"&",b,"is: ",c)

#Multiplication
c=a*b
print("Multiplication of",a,"&",b,"is: ",c)

#Division
c=a/b
print("Division of",a,"&",b,"is: ",c)

#Exponential
c=a**b
print("Exponential of",a,"&",b,"is: ",c)

#Modulus
c=a%b
print("Modulus of",a,"&",b,"is: ",c)

#Floor Division
c=a//b
print("Floor Division of",a,"&",b,"is: ",c)
